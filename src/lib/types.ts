// Shared types used by both the server pipeline and the UI.

export type AspectRatio = "9:16" | "16:9";
export type NarrationLanguage = "ar" | "en";

export type StageName = "story" | "scenes" | "characters" | "images" | "voice" | "videos" | "music" | "render";

// Voice runs before animation so each clip can be generated at the narration's length.
export const STAGE_ORDER: StageName[] = ["story", "scenes", "characters", "images", "voice", "videos", "music", "render"];

export const STAGE_LABELS: Record<StageName, string> = {
  story: "Story",
  scenes: "Scenes",
  characters: "Characters",
  images: "Images",
  videos: "Animation",
  voice: "Voiceover",
  music: "Music & SFX",
  render: "Final render",
};

export type AssetStatus = "idle" | "queued" | "running" | "done" | "error";

export interface AssetState {
  status: AssetStatus;
  /** Path relative to the project directory */
  file?: string;
  error?: string;
  /** Provider that produced the asset, e.g. "fal:fal-ai/kling-video/..." */
  provider?: string;
  updatedAt?: string;
  /** Duration in seconds for audio/video assets */
  duration?: number;
}

export interface Character {
  id: string;
  name: string;
  /** Canonical visual description injected verbatim into every prompt featuring this character */
  appearance: string;
  /** Personality / role, used by the LLM only */
  role: string;
  reference: AssetState;
}

export interface Scene {
  id: string;
  index: number;
  title: string;
  /** Spoken narration for this scene (in project language / dialect) */
  narration: string;
  /** What happens visually */
  visual: string;
  /** Camera direction, e.g. "slow push-in, low angle" */
  camera: string;
  /** Lighting / mood */
  mood: string;
  /** What moves during the clip (for image-to-video) */
  motion: string;
  /** Short description of sound effects for the scene */
  sfx: string;
  /** IDs of characters present in this scene */
  characterIds: string[];
  /** Target duration in seconds (actual length follows the voiceover when present) */
  duration: number;
  /** Final prompts (generated by the style engine, editable) */
  imagePrompt: string;
  motionPrompt: string;
  image: AssetState;
  video: AssetState;
  voice: AssetState;
  sfxAudio: AssetState;
}

export interface StoryDraft {
  title: string;
  logline: string;
  /** Full narration text */
  script: string;
}

export interface ProjectSettings {
  aspectRatio: AspectRatio;
  fps: number;
  /** Target total duration in seconds */
  targetDuration: number;
  language: NarrationLanguage;
  /** Free text, e.g. "Moroccan Darija", "Modern Standard Arabic with full diacritics" */
  dialect: string;
  subtitles: boolean;
  musicPrompt: string;
  musicVolume: number; // 0..1
  sfxEnabled: boolean;
  transitionSeconds: number;
}

export interface StageState {
  status: AssetStatus;
  progress: number; // 0..1
  message?: string;
  error?: string;
  startedAt?: string;
  finishedAt?: string;
}

export interface Project {
  id: string;
  name: string;
  idea: string;
  createdAt: string;
  updatedAt: string;
  settings: ProjectSettings;
  story?: StoryDraft;
  characters: Character[];
  scenes: Scene[];
  music: AssetState;
  final: AssetState;
  stages: Record<StageName, StageState>;
  /** Id of the job currently running for this project, if any */
  activeJob?: string;
  log: { at: string; level: "info" | "error"; message: string }[];
}

