// ---- Provider configuration (secrets never leave the server) ----

export type LlmProviderId = "anthropic";
export type ImageProviderId = "openai" | "fal";
export type VideoProviderId = "fal" | "local-motion";
export type TtsProviderId = "elevenlabs" | "openai" | "gemini";
export type MusicProviderId = "none" | "fal" | "elevenlabs" | "upload";
export type SfxProviderId = "none" | "elevenlabs";

export interface ProviderSettings {
  llm: { provider: LlmProviderId; model: string; effort: "low" | "medium" | "high" | "xhigh" | "max" };
  image: {
    provider: ImageProviderId;
    openaiModel: string;
    falModel: string;
    /** fal model used when a character reference image should be followed (image editing / reference model) */
    falReferenceModel: string;
  };
  video: { provider: VideoProviderId; falModel: string; clipSeconds: number };
  tts: {
    provider: TtsProviderId;
    elevenlabsVoiceId: string;
    elevenlabsModel: string;
    openaiModel: string;
    openaiVoice: string;
    geminiModel: string;
    geminiVoice: string;
    /** Delivery instructions for TTS engines that accept them */
    styleInstructions: string;
  };
  music: { provider: MusicProviderId; falModel: string };
  sfx: { provider: SfxProviderId };
}

export const SECRET_KEYS = ["ANTHROPIC_API_KEY", "OPENAI_API_KEY", "FAL_KEY", "ELEVENLABS_API_KEY", "GEMINI_API_KEY"] as const;
export type SecretKey = (typeof SECRET_KEYS)[number];

export interface PublicSettings {
  providers: ProviderSettings;
  /** For each secret: where it comes from and a masked preview — never the value */
  secrets: Record<SecretKey, { configured: boolean; source: "env" | "saved" | "none"; preview?: string }>;
  ffmpeg: { available: boolean; version?: string };
}

